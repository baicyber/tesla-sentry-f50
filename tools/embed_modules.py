#!/usr/bin/env python3
"""把本地模块 (storage_allocation / storage_resize) 压缩内嵌进 sentry-viewer.py。

为什么需要: 主程序在顶层 import 这两个模块。旧版 OTA 只会下发 sentry-viewer.py 单文件,
升级后模块缺失 -> ImportError -> 服务起不来。内嵌一份 gzip+base64 副本作为兜底,
文件存在时仍优先用文件 (可单独热修), 文件缺失时用内嵌副本继续跑。

用法:
    python3 tools/embed_modules.py            # 就地更新 sentry-viewer.py 里的 _EMBED_MODULES
    python3 tools/embed_modules.py --check     # 只校验内嵌副本与磁盘文件是否一致 (CI/测试用)
"""
import base64
import gzip
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
TARGET = os.path.join(ROOT, "sentry-viewer.py")
MODULES = ("storage_allocation.py", "storage_resize.py")

BEGIN = "# >>> embedded local modules (auto-generated by tools/embed_modules.py) >>>"
END = "# <<< embedded local modules <<<"


def _b64(path):
    with open(path, "rb") as f:
        raw = f.read()
    # mtime=0 让同一份源码每次都生成完全相同的字节, 避免无意义的 diff
    return base64.b64encode(gzip.compress(raw, 9, mtime=0)).decode("ascii")


def render():
    lines = [BEGIN,
             "# 内嵌副本: 仅当同目录找不到同名 .py 时启用 (旧版 OTA 只下发主程序的兼容路径)",
             "_EMBED_MODULES = {"]
    for name in MODULES:
        blob = _b64(os.path.join(ROOT, name))
        key = name[:-3]
        lines.append('    "%s": (' % key)
        for i in range(0, len(blob), 96):
            lines.append('        "%s"' % blob[i:i + 96])
        lines.append("    ),")
    lines.append("}")
    lines.append(END)
    return "\n".join(lines)


def main():
    check = "--check" in sys.argv
    with open(TARGET, encoding="utf-8") as f:
        src = f.read()
    block = render()
    pat = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    m = pat.search(src)
    if check:
        if not m:
            print("FAIL: 主程序里没有内嵌模块块, 先跑 python3 tools/embed_modules.py")
            return 1
        if m.group(0) != block:
            print("FAIL: 内嵌副本与 storage_*.py 不一致, 请重跑 python3 tools/embed_modules.py")
            return 1
        print("ok: 内嵌模块与磁盘文件一致 (%d 个)" % len(MODULES))
        return 0
    if m:
        src = src[:m.start()] + block + src[m.end():]
    else:
        anchor = "sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))"
        if anchor not in src:
            print("FAIL: 找不到插入锚点 %r" % anchor)
            return 1
        src = src.replace(anchor, block + "\n" + anchor, 1)
    with open(TARGET, "w", encoding="utf-8", newline="\n") as f:
        f.write(src)
    print("ok: 已写入 %d 个内嵌模块 (%.1f KB base64)" % (len(MODULES), len(block) / 1024))
    return 0


if __name__ == "__main__":
    sys.exit(main())
