"""内嵌模块副本必须与磁盘上的 storage_*.py 一致。

主程序为了让"只下发单文件的旧 OTA"也能升级, 把两个模块 gzip+base64 内嵌了一份。
模块改了却忘记重跑 `python3 tools/embed_modules.py`, 设备就会用到旧代码 —— 这里守住。
"""
import base64
import gzip
import re
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
MODULES = ('storage_allocation', 'storage_resize')


def embedded_source():
    src = (REPO / 'sentry-viewer.py').read_text(encoding='utf-8')
    begin = '# >>> embedded local modules (auto-generated by tools/embed_modules.py) >>>'
    end = '# <<< embedded local modules <<<'
    start, stop = src.index(begin), src.index(end)
    block = src[start:stop]
    out = {}
    for name in MODULES:
        m = re.search(r'"%s": \((.*?)\n    \),' % name, block, re.S)
        if not m:
            raise AssertionError('主程序里找不到 %s 的内嵌副本' % name)
        b64 = ''.join(re.findall(r'"([^"]*)"', m.group(1)))
        out[name] = gzip.decompress(base64.b64decode(b64))
    return out, block


class EmbeddedModulesTest(unittest.TestCase):
    def test_embedded_matches_repo_files(self):
        got, _ = embedded_source()
        for name in MODULES:
            with self.subTest(module=name):
                want = (REPO / (name + '.py')).read_bytes()
                self.assertEqual(got[name], want,
                                 '%s.py 与内嵌副本不一致, 请运行 python3 tools/embed_modules.py' % name)

    def test_embedded_source_compiles(self):
        got, _ = embedded_source()
        for name, data in got.items():
            with self.subTest(module=name):
                compile(data, '<embedded:%s>' % name, 'exec')

    def test_bootstrap_falls_back_to_embedded(self):
        """主程序里必须留着 "找不到文件就用内嵌副本" 的分支, 否则旧 OTA 升级后起不来"""
        src = (REPO / 'sentry-viewer.py').read_text(encoding='utf-8')
        self.assertIn('def _load_embedded_module(', src)
        self.assertIn('_load_embedded_module(_mod_name)', src)
        self.assertIn('gzip.decompress', src)


if __name__ == '__main__':
    unittest.main()
